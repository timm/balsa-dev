#!/usr/bin/env python3 -B
"""actvar: the optimizer study's variance table, for the back of the paper.

Same four-way split as Table 7 -- data set, learner, fold, interaction --
run group by group over the folders of moot/optimize, on the win score of
the active-learning study.  The learners are the four an optimizer author
would pick between: 1nn, LightGBM, balsa(30) and TabICL.  `random` is the
floor, not a choice, and balsa(1) is the crippled single tree, so neither
belongs in a split that asks what separates real options.

usage: python3 actvar.py runs/active*.txt > actvar.tex
"""
import sys, statistics as st, collections

ARMS = {"a.knn": "1nn", "a.lgbm": "lgbm(100)",
        "a.b30": "balsa(30)", "a.tabicl": "TabICL"}


def split(F, sets, arms):
    I, J = len(sets), len(arms)
    R = len(F[sets[0]][arms[0]])
    y = [v for s in sets for a in arms for v in F[s][a]]
    hat = st.fmean(y)
    row  = {s: st.fmean([v for a in arms for v in F[s][a]]) for s in sets}
    col  = {a: st.fmean([v for s in sets for v in F[s][a]]) for a in arms}
    cell = {(s, a): st.fmean(F[s][a]) for s in sets for a in arms}
    tot  = sum((v - hat) ** 2 for v in y)
    d = 100 * J * R * sum((row[s] - hat) ** 2 for s in sets) / tot
    m = 100 * I * R * sum((col[a] - hat) ** 2 for a in arms) / tot
    f = 100 * sum((v - cell[(s, a)]) ** 2
                  for s in sets for a in arms for v in F[s][a]) / tot
    return d, m, f, 100 - d - m - f


def main():
    F = {}
    for p in sys.argv[1:]:
        for l in open(p):
            if not l.startswith("%folds"): continue
            _, s, a, *v = l.split()
            if a in ARMS: F.setdefault(s, {})[ARMS[a]] = [float(x) for x in v]
    arms = tuple(ARMS.values())
    full = sorted(s for s in F if all(a in F[s] for a in arms))
    G = collections.defaultdict(list)
    for s in full: G[s.split("/")[0]].append(s)

    def row(name, sets):
        d, m, f, o = split(F, sorted(sets), arms)
        return (f"{name.replace('_', chr(92) + '_')} & {len(sets)} & {d:.0f}"
                f" & {m:.0f} & {f:.0f} & {o:.0f} & {d / m:.0f} \\\\", m)

    body = sorted((row(g, ss) for g, ss in G.items() if len(ss) >= 2),
                  key=lambda t: t[1])          # least learner-effect first
    print(r"""% GENERATED by balsa-dev/actvar.py -- do not edit here.
\begin{table}[t]
\caption{Table~\ref{box:variance}'s four-way split, run group by group
over the optimizer study of \S\ref{sec:active}, on the win score of
Figure~\ref{fig:allact}. Learners are the four an optimizer author would
choose between: {\tt 1nn}, LightGBM, {\tt balsa(30)} and TabICL. {\em
random} is the floor rather than a choice, and {\tt balsa(1)} is a
crippled single tree, so neither belongs in a split that asks what
separates real options. Groups are the folders of {\tt moot/optimize},
ordered by their {\em learner} share, and only groups with two or more
sets are listed. {\em d/l} is {\em data}/{\em learner}.}
\label{tab:actvar}
\centering
{\scriptsize
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lrrrrrr}
\toprule
group & sets & {\em data} & {\em learner} & {\em fold} & {\em other}
      & {\em d/l} \\
\midrule""")
    print("\n".join(t for t, _ in body))
    print(r"\cmidrule{1-7}")
    print(row("all sets", full)[0])
    print(r"""\bottomrule
\end{tabular}
}
\end{table}""")
    d, m, f, o = split(F, full, arms)
    print(f"% all: data {d:.0f} learner {m:.0f} fold {f:.0f} other {o:.0f}",
          file=sys.stderr)


if __name__ == "__main__": main()
