#!/usr/bin/env python3 -B
"""sesoi: how the TabICL result survives a rising "worth caring about" floor.

A significance test answers "is this difference real?"  With 98 data sets
and ten folds each, almost any difference is.  The question a reader
actually has is "is it big enough to pay for?", and that needs a
threshold declared in advance: a SESOI, the smallest effect size of
interest.  The rig already has one -- `prudence`, the floor under which
two means are never called different -- but at 0.01 it admits anything.

This sweeps it.  For each study, the per-set difference between TabICL
and the method this paper recommends is counted three ways: TabICL ahead
by more than the floor, inside the floor (a tie), or behind by more than
it.  The floor is given in each study's own units and, so the three can
be read on one scale, as a multiple of that study's median fold noise.

That noise is the spread of the per-fold DIFFERENCE, not the spread of
either arm on its own.  The comparison is paired -- both arms see the
same folds, so their errors move together -- and the difference is what
is being thresholded.  The distinction is not academic: on the optimizer
study the paired spread is 4.4 win points where one arm alone reads 3.2,
so using one arm would have flattered TabICL by 39% exactly where it
deserved the least slack.

usage: python3 sesoi.py > sesoi.tex
"""
import csv, glob, sys, statistics as st, collections

KS = (0, .5, 1, 1.5, 2)          # SESOI, in median-fold-sd units
PRU = 0.01                       # the rig's current prudence


def spread(v):
    v = sorted(v); n = len(v)
    q = lambda p: v[min(n - 1, int(p * n))]
    return (q(.9) - q(.1)) / 2.56


def classification():
    F = {}
    for p in ("runs/nose39-yue.txt", "runs/se61-yue.txt"):
        for l in open(p):
            if l.startswith("%folds"):
                _, s, a, *v = l.split()
                F.setdefault(s, {})[a] = [float(x) for x in v]
    d = [st.fmean(F[s]["tabicl"]) - st.fmean(F[s]["n30"]) for s in F]
    sd = st.median([spread([x - y for x, y in zip(F[s]["tabicl"], F[s]["n30"])])
                    for s in F])
    return d, sd, "AUC points", 2


def regression():
    D = collections.defaultdict(list)
    for p in ("runs/reg56.csv", "runs/sereg.csv"):
        for r in csv.DictReader(open(p)): D[r["data"]].append(r)
    ok = [s for s in D if all(r.get("rel_tabicl", "") != "" for r in D[s])]
    d = [st.fmean([float(r["rel_tree30"]) for r in D[s]])
         - st.fmean([float(r["rel_tabicl"]) for r in D[s]]) for s in ok]
    sd = st.median([spread([float(r["rel_tree30"]) - float(r["rel_tabicl"])
                            for r in D[s]]) for s in ok])
    return d, sd, "rel", 3


def optimization():
    G = {}
    for p in glob.glob("runs/active*.txt"):
        for l in open(p):
            if l.startswith("%folds"):
                _, s, a, *v = l.split()
                G.setdefault(s, {})[a] = [float(x) for x in v]
    ok = [s for s in G if "a.tabicl" in G[s] and "a.knn" in G[s]]
    d = [st.fmean(G[s]["a.tabicl"]) - st.fmean(G[s]["a.knn"]) for s in ok]
    sd = st.median([spread([x - y for x, y in
                            zip(G[s]["a.tabicl"], G[s]["a.knn"])]) for s in ok])
    return d, sd, "win points", 2


def main():
    print(r"""% GENERATED by tree-dev/sesoi.py -- do not edit here.
\begin{table}[t]
\caption{What survives a rising floor. For each study, the per-set
difference between TabICL and the method this paper recommends ({\tt
tree(30)}, or {\tt 1nn} for optimization), counted against a {\em
smallest effect size of interest}: TabICL {\em ahead} by more than the
floor, {\em tied} inside it, or {\em behind} by more than it. The floor
is given in each study's own units and as a multiple of that study's
median paired fold sd, so the three can be read on one scale --- a difference
smaller than the noise of one's own measurement is not one to pay for.
The first row of each block is the rig's current {\tt prudence} of 0.01,
which is effectively no floor at all. The {\em break-even} in each
block header is the floor at which TabICL
stops leading on most sets. It is just the median difference: half the
sets lie above it by construction, so one number answers {\em how much
would a reader have to stop caring about before this method stops
winning?} Whether three AUC points is worth buying depends on what it
is set against, and this paper supplies the scale: {\tt tree(30)}
differs from LightGBM by $0.2$ points, TabICL beats {\tt tree(30)} by
$3.3$, and going from one tree to thirty was worth $10.7$. TabICL's
edge is thus about a third of what our own ensembling already bought,
and the optimizer's break-even of one win point is smaller still.
(The floor at which ties outnumber wins sits within a hair of it ---
1.70, 2.11 and 0.27 sd --- because so few sets go the other way.)
Compare the cost of buying those wins: Figure~\ref{fig:loc}(b)--(d).}
\label{tab:sesoi}
\centering
{\scriptsize
\setlength{\tabcolsep}{4.5pt}
\begin{tabular}{lrrrr}
\toprule
floor & in units & {\em ahead} & {\em tied} & {\em behind} \\
\midrule""")
    for nm, fn, n_lab in (("classification", classification, "98 sets"),
                          ("regression", regression, "69 sets"),
                          ("optimization", optimization, "62 sets")):
        d, sd, units, dp = fn()
        n = len(d)
        med = st.median(d)
        print(f"\\multicolumn{{5}}{{l}}{{\\em {nm}}}, {n} sets, {units};"
              f" paired sd {sd:.{dp}f}; {{\\bf break-even}}"
              f" {med:+.{dp}f} $= {med/sd:.2f}$ sd \\\\")
        for k in KS:
            S = PRU if k == 0 else k * sd
            tag = r"{\tt prudence}" if k == 0 else f"${k:g}\\times$sd"
            w = sum(1 for x in d if x > S)
            t = sum(1 for x in d if abs(x) <= S)
            L = sum(1 for x in d if x < -S)
            print(f"\\quad {tag} & {S:.{dp}f} & {w} ({100*w/n:.0f}\\%)"
                  f" & {t} ({100*t/n:.0f}\\%) & {L} ({100*L/n:.0f}\\%) \\\\")
        if nm != "optimization": print(r"\cmidrule{1-5}")
    print(r"""\bottomrule
\end{tabular}
}
\end{table}""")


if __name__ == "__main__": main()
