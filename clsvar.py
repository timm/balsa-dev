#!/usr/bin/env python3 -B
"""clsvar: the classification twin of the regression variance table.

Table 7 of the paper defines a four-way split of the variance in a score
-- data set, learner, fold, interaction -- and reports it once, over
every data set at once.  This runs the same split group by group, so the
reader can see that the one headline number is not hiding a group where
the learner wins.  The regression section has the same table on rel; this
is the one on AUC, and the two use the same three learners so they can be
read against each other.

balsa(1) is excluded, as in the paper's headline: a deliberately crippled
single tree would inflate the learner share with a gap nobody is choosing
between.  Two sets are excluded as well -- TabICL's per-fold timeout fired
on them, and an unbalanced two-way layout does not decompose
orthogonally, so the four shares would not sum to 100.

The output is a LaTeX file for \\input, numbers and all, so the table
cannot drift from the runs behind it.

usage: python3 clsvar.py runs/nose39-yue.txt runs/se61-yue.txt > clsvar.tex
"""
import sys, statistics as st

ARMS    = ("lgbm", "n30", "tabicl")
PARTIAL = {"bank-marketing", "adult"}
# group name -> how to find its sets in the two run files.  The non-SE
# file is in group order, ten at a time; the SE file is by path.
NOSE = [("numeric", 0, 10), ("symbolic", 10, 20), ("mixed", 20, 30),
        ("large", 30, 39)]
SE   = [("issues", "se/issues/"), ("smells", "se/smells/"),
        ("defects", "se/defect"), ("static", "se/static")]


def folds(path):
    "Every %folds line: set -> arm -> its R fold AUCs, in file order."
    out = {}
    for line in open(path):
        if not line.startswith("%folds"): continue
        _, f, arm, *vals = line.split()
        out.setdefault(f, {})[arm] = [float(v) for v in vals]
    return out


def split(sets, src):
    "eta-squared for data set, learner, fold, interaction.  Sums to 100."
    I, J = len(sets), len(ARMS)
    R = len(src[sets[0]][ARMS[0]])
    y = [v for f in sets for a in ARMS for v in src[f][a]]
    hat = st.fmean(y)
    row  = {f: st.fmean([v for a in ARMS for v in src[f][a]]) for f in sets}
    col  = {a: st.fmean([v for f in sets for v in src[f][a]]) for a in ARMS}
    cell = {(f, a): st.fmean(src[f][a]) for f in sets for a in ARMS}
    tot  = sum((v - hat) ** 2 for v in y)
    d = 100 * J * R * sum((row[f] - hat) ** 2 for f in sets) / tot
    m = 100 * I * R * sum((col[a] - hat) ** 2 for a in ARMS) / tot
    k = 100 * sum((v - cell[(f, a)]) ** 2
                  for f in sets for a in ARMS for v in src[f][a]) / tot
    return d, m, k, 100 - d - m - k


def main():
    nose, se = folds(sys.argv[1]), folds(sys.argv[2])
    order  = [f for f in nose if f not in PARTIAL]
    groups  = [(n, order[a:b], nose) for n, a, b in NOSE]
    groups += [(n, [f for f in se if f.startswith(p)], se) for n, p in SE]
    allsets = {f: src[f] for _, s, src in groups for f in s}

    def row(name, sets, src):
        d, m, k, o = split(sorted(sets), src)
        return (f"{name} & {len(sets)} & {d:.0f} & {m:.0f} & {k:.0f}"
                f" & {o:.0f} & {d / m:.0f} \\\\")

    body = [row(n, s, src) for n, s, src in groups if s]
    body.append(r"\cmidrule{1-7}")
    body.append(row("all sets", list(allsets), allsets))

    print(r"""% GENERATED by balsa-dev/clsvar.py -- do not edit here.
\begin{table}[t]
\caption{Table~\ref{box:variance}'s split, run group by group over the
classification corpus, so the one number in that box can be checked
against the parts it averages. {\em data}, {\em learner} and {\em fold}
are $\eta^2$ percentages; {\em other} is what those three leave, the
interaction between learner and data set. The last column is {\em
data}/{\em learner}. The learners are LightGBM, {\tt balsa(30)} and
TabICL --- the three a reader is choosing between; {\tt balsa(1)} is
left out, since a deliberately crippled single tree would inflate the
learner share with a gap nobody is weighing. Two sets are left out as
well: TabICL's per-fold timeout fired on {\tt bank-marketing} and {\tt
adult}, and an unbalanced layout does not decompose orthogonally, so the
shares would not sum to 100. Table~\ref{tab:regvar} is the same table on
regression.}
\label{tab:clsvar}
\centering
{\scriptsize
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lrrrrrr}
\toprule
group & sets & {\em data} & {\em learner} & {\em fold} & {\em other}
      & {\em d/l} \\
\midrule""")
    print("\n".join(body))
    print(r"""\bottomrule
\end{tabular}
}
\end{table}""")

    print("\n% plainly:", file=sys.stderr)
    for n, s, src in groups + [("all sets", list(allsets), allsets)]:
        if not s: continue
        d, m, k, o = split(sorted(s), src)
        print(f"%   {n:10s} {len(s):3d} sets  data {d:3.0f}  learner {m:3.0f}"
              f"  fold {k:3.0f}  other {o:3.0f}   {d / m:4.0f}x",
              file=sys.stderr)


if __name__ == "__main__": main()
