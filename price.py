#!/usr/bin/env python3 -B
"""price: what one point of score costs, from each supplier.

"Is five AUC points worth a thousand times the CPU?" is a question of
taste until someone quotes a price.  This does: for each study, take the
treatments in order of score and report the marginal cost of each step
-- the extra seconds divided by the extra points they bought.

The result is the paper's cost argument in one number.  The step from
one tree to thirty buys ten AUC points at two seconds each.  The step
from thirty trees to a pretrained transformer buys four more at eight
thousand seconds each.  Both are real gains; they are not the same
purchase.

usage: python3 price.py > price.tex
"""
import csv, glob, statistics as st, collections


def cls():
    F, secs = {}, {}
    for p in ("runs/nose39-yue.txt", "runs/se61-yue.txt"):
        head = open(p).readline().split()[1:]
        for l in open(p):
            if l.startswith("%folds"):
                _, s, a, *v = l.split()
                F.setdefault(s, {})[a] = [float(x) for x in v]
            elif l.startswith("#secs"):
                for h, x in zip(head, l.split()[3:]):
                    secs[h] = secs.get(h, 0) + float(x)
    mu = {a: st.fmean([st.fmean(F[s][a]) for s in F])
          for a in ("1:q16", "n30", "lgbm", "tabicl")}
    return ("classification", "AUC point",
            [(r"{\tt enuf(1)}", mu["1:q16"], secs["1:q16"]),
             (r"{\tt enuf(30)}", mu["n30"], secs["n30"]),
             ("LightGBM", mu["lgbm"], secs["lgbm"]),
             ("TabICL", mu["tabicl"], secs["tabicl"])])


def reg():
    D, secs = collections.defaultdict(list), {}
    for p in ("runs/reg56.csv", "runs/sereg.csv"):
        for r in csv.DictReader(open(p)): D[r["data"]].append(r)
        t = p.rsplit(".", 1)[0] + ".txt"
        head = open(t).readline().split()[1:]
        for l in open(t):
            if l.startswith("#secs"):
                for h, x in zip(head, l.split()[3:]):
                    secs[h] = secs.get(h, 0) + float(x)
    for q in ("runs/reg56-tabicl.txt", "runs/sereg-tabicl.txt"):
        for l in open(q):
            if l.startswith("#secs"):
                secs["TabICL"] = secs.get("TabICL", 0) + float(l.split()[-1])
    ok = [s for s in D if all(r.get("rel_tabicl", "") != "" for r in D[s])]
    # as "goodness": 100*(1-rel), so a point here is 0.01 of rel
    f = lambda k: 100 * (1 - st.fmean([st.fmean([float(r[k]) for r in D[s]])
                                       for s in ok]))
    return ("regression", "0.01 of rel",
            [(r"{\tt enuf(1)}", f("rel_enuf1"), secs["enuf(1)"]),
             (r"{\tt enuf(30)}", f("rel_enuf30"), secs["enuf(30)"]),
             ("LightGBM", f("rel_lgbm"), secs["lgbm"]),
             ("TabICL", f("rel_tabicl"), secs["TabICL"])])


def act():
    G, S = {}, collections.defaultdict(float)
    for p in glob.glob("runs/active*.txt"):
        for l in open(p):
            if l.startswith("%folds"):
                _, s, a, *v = l.split()
                G.setdefault(s, {})[a] = [float(x) for x in v]
            elif l.startswith("%secs"):
                _, s, a, *v = l.split(); S[a] += sum(map(float, v))
    ok = [s for s in G if "a.tabicl" in G[s] and "a.knn" in G[s]]
    g = lambda a: st.fmean([st.fmean(G[s][a]) for s in ok])
    return ("optimization", "win point",
            [(r"{\tt enuf(1)}", g("a.b1"), S["a.b1"]),
             (r"{\tt enuf(30)}", g("a.b30"), S["a.b30"]),
             (r"{\tt 1nn}", g("a.knn"), S["a.knn"]),
             ("LightGBM", g("a.lgbm"), S["a.lgbm"]),
             ("TabICL", g("a.tabicl"), S["a.tabicl"])])


def main():
    print(r"""% GENERATED by enuf-dev/price.py -- do not edit here.
\begin{table}[t]
\caption{The trade space: what additional performance costs. Within each
study the treatments are sorted by run time, cheapest first, and a
treatment is {\em dominated} when something cheaper already scored at
least as well --- no budget buys it. The rest form the frontier, and for
those the last column prices the step up from the previous frontier
point: extra seconds divided by extra score. {\em Is five AUC points
worth a thousand times the CPU?} is a matter of taste until someone
quotes a price; this quotes it. Seconds are summed over folds, one
thread each, as in Figure~\ref{fig:loc}.}
\label{tab:price}
\centering
{\scriptsize
\setlength{\tabcolsep}{5pt}
\begin{tabular}{lrrl r}
\toprule
treatment & score & secs & & secs per extra point \\
\midrule""")
    for name, unit, rows in (cls(), reg(), act()):
        print(f"\\multicolumn{{5}}{{l}}{{\\em {name}}}, one point $=$ one"
              f" {unit} \\\\")
        best, prev = -1e9, None
        for n, sc, c in sorted(rows, key=lambda r: r[2]):
            if sc > best:
                if prev is None:
                    price = "---"
                else:
                    v = (c - prev[1]) / (sc - prev[0])
                    price = "$<1$" if v < 1 else f"{v:,.0f}"
                print(f"\\quad {n} & {sc:.1f} & {c:,.0f} & & {price} \\\\")
                best, prev = sc, (sc, c)
            else:
                print(f"\\quad {n} & {sc:.1f} & {c:,.0f} &"
                      f" {{\\em dominated}} & \\\\")
        if name != "optimization": print(r"\cmidrule{1-5}")
    print(r"""\bottomrule
\end{tabular}
}
\end{table}""")


if __name__ == "__main__": main()
